#Write a program that performs the four basic arithmetic operations using separate functions.


def addition(a , b):
    c = a + b
    return c 


def subtraction(a , b):
    c = a - b
    return c 

def multiplication(a , b):
    c = a * b
    return c 

def division(a , b):
    c = a / b
    return c 

print(addition(12 , 6))
print(subtraction(5 , 6))
print(multiplication(12 , 6))
print(division(12 , 3))